"""Per-page text extraction with scanned/suspect page detection.

Usage: python -m ph_privacy_guide.ingest.extract

Writes:
  data/processed/pages/<doc_id>.jsonl   one record per page (gitignored)
  reports/extraction_report.csv         one row per page
  reports/extraction_report.md          one row per document + flagged pages

Page classification (no OCR is ever attempted):
  ok       text layer looks normal
  scanned  < MIN_CHARS extractable characters and images cover >= SCAN_IMAGE_COVER of the page
  empty    < MIN_CHARS characters and no large image (blank or separator page)
  suspect  text present but garbled: (cid:NN) glyphs, low letter ratio, or few word-like tokens
Scanned, empty and suspect pages are excluded from chunking and listed in the report.
"""
from __future__ import annotations

import csv
import json
import re
from dataclasses import asdict, dataclass

import pdfplumber

from ph_privacy_guide.config import PROCESSED, RAW, REPORTS, allowed_pdfs

MIN_CHARS = 50
SCAN_IMAGE_COVER = 0.70
MIN_ALPHA_RATIO = 0.60     # letters / non-space chars
MIN_WORDLIKE_RATIO = 0.70  # tokens that look like words / all tokens

CID_RE = re.compile(r"\(cid:\d+\)")
TOKEN_RE = re.compile(r"\S+")
WORDLIKE_RE = re.compile(r"^[\(\[\"'“‘]*[A-Za-zÑñ][A-Za-zÑñ'’\-]*[A-Za-zÑñ]?[\)\]\"'”’.,;:!?]*$|^[\(\[]?\d+[\)\].,;:]*$|^[\(\[]?[a-zA-Z0-9]{1,4}[\)\].]$")


def doc_id_for(path) -> str:
    return path.stem


@dataclass
class PageStat:
    doc_id: str
    collection: str
    page: int
    chars: int
    image_cover: float
    cid_glyphs: int
    alpha_ratio: float
    wordlike_ratio: float
    status: str
    reason: str


def _image_cover(page) -> float:
    area = float(page.width * page.height) or 1.0
    covered = 0.0
    for im in page.images:
        w = max(0.0, min(im["x1"], page.width) - max(im["x0"], 0))
        h = max(0.0, min(im["bottom"], page.height) - max(im["top"], 0))
        covered += w * h
    return min(1.0, covered / area)


def classify(text: str, image_cover: float) -> tuple[str, str, int, float, float]:
    stripped = text.strip()
    nonspace = re.sub(r"\s", "", stripped)
    cid = len(CID_RE.findall(stripped))
    alpha = sum(c.isalpha() for c in nonspace) / len(nonspace) if nonspace else 0.0
    toks = TOKEN_RE.findall(stripped)
    wordlike = sum(bool(WORDLIKE_RE.match(t)) for t in toks) / len(toks) if toks else 0.0
    if len(nonspace) < MIN_CHARS:
        if image_cover >= SCAN_IMAGE_COVER:
            return "scanned", f"{len(nonspace)} chars, images cover {image_cover:.0%}", cid, alpha, wordlike
        return "empty", f"{len(nonspace)} chars, no full-page image", cid, alpha, wordlike
    reasons = []
    if cid:
        reasons.append(f"{cid} (cid:NN) glyphs")
    if alpha < MIN_ALPHA_RATIO:
        reasons.append(f"letter ratio {alpha:.2f}")
    if wordlike < MIN_WORDLIKE_RATIO:
        reasons.append(f"word-like ratio {wordlike:.2f}")
    if reasons:
        return "suspect", "; ".join(reasons), cid, alpha, wordlike
    return "ok", "", cid, alpha, wordlike


def extract_all() -> list[PageStat]:
    pages_dir = PROCESSED / "pages"
    pages_dir.mkdir(parents=True, exist_ok=True)
    stats: list[PageStat] = []
    for pdf_path in allowed_pdfs():
        doc_id = doc_id_for(pdf_path)
        collection = pdf_path.relative_to(RAW).parts[0]
        with pdfplumber.open(pdf_path) as pdf, open(pages_dir / f"{doc_id}.jsonl", "w") as out:
            for i, page in enumerate(pdf.pages, start=1):
                text = page.extract_text() or ""
                cover = _image_cover(page)
                status, reason, cid, alpha, wordlike = classify(text, cover)
                st = PageStat(doc_id, collection, i, len(re.sub(r"\s", "", text)), round(cover, 3),
                              cid, round(alpha, 3), round(wordlike, 3), status, reason)
                stats.append(st)
                out.write(json.dumps({"doc_id": doc_id, "page": i, "status": status, "text": text},
                                     ensure_ascii=False) + "\n")
    return stats


def write_reports(stats: list[PageStat]) -> None:
    REPORTS.mkdir(exist_ok=True)
    with open(REPORTS / "extraction_report.csv", "w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=list(asdict(stats[0]).keys()))
        w.writeheader()
        for s in stats:
            w.writerow(asdict(s))

    by_doc: dict[str, list[PageStat]] = {}
    for s in stats:
        by_doc.setdefault(s.doc_id, []).append(s)

    lines = [
        "# Extraction report",
        "",
        "Generated by `python -m ph_privacy_guide.ingest.extract` (pdfplumber). Text length = non-whitespace "
        "characters. No OCR is performed; scanned, empty and suspect pages are excluded from chunking.",
        f"Thresholds: scanned = <{MIN_CHARS} chars and images ≥{SCAN_IMAGE_COVER:.0%} of page; "
        f"suspect = (cid) glyphs, letter ratio <{MIN_ALPHA_RATIO}, or word-like ratio <{MIN_WORDLIKE_RATIO}.",
        "",
        "| Collection | Document | Pages | Text chars | OK | Scanned | Empty | Suspect |",
        "|---|---|---:|---:|---:|---:|---:|---:|",
    ]
    tot = {"pages": 0, "chars": 0, "ok": 0, "scanned": 0, "empty": 0, "suspect": 0}
    for doc_id, ps in by_doc.items():
        c = {k: sum(p.status == k for p in ps) for k in ("ok", "scanned", "empty", "suspect")}
        chars = sum(p.chars for p in ps)
        lines.append(f"| {ps[0].collection} | {doc_id} | {len(ps)} | {chars:,} | {c['ok']} | "
                     f"{c['scanned'] or ''} | {c['empty'] or ''} | {c['suspect'] or ''} |")
        tot["pages"] += len(ps); tot["chars"] += chars
        for k in c:
            tot[k] += c[k]
    lines.append(f"| **all** | **{len(by_doc)} documents** | **{tot['pages']}** | **{tot['chars']:,}** | "
                 f"**{tot['ok']}** | **{tot['scanned']}** | **{tot['empty']}** | **{tot['suspect']}** |")
    flagged = [s for s in stats if s.status != "ok"]
    lines += ["", "## Flagged pages", ""]
    if flagged:
        lines += ["| Document | Page | Status | Reason |", "|---|---:|---|---|"]
        lines += [f"| {s.doc_id} | {s.page} | {s.status} | {s.reason} |" for s in flagged]
    else:
        lines.append("None.")
    (REPORTS / "extraction_report.md").write_text("\n".join(lines) + "\n")


def main() -> None:
    stats = extract_all()
    write_reports(stats)
    print((REPORTS / "extraction_report.md").read_text())


if __name__ == "__main__":
    main()

#!/usr/bin/env python3
"""Find repeal, supersede, amend and supplement language in all 28 corpus documents.

Usage: .venv/bin/python scripts/scan_status_language.py
Writes reports/status_language_scan.md and .csv. Changes no status.

Reads every record kind, including preambles, footnotes, signature blocks and annexes. Each hit is
classed by the sentence's own wording:
  named    names another instrument
  generic  a "contrary or inconsistent" style clause, or names nothing; never a basis for a status change
"""
from __future__ import annotations

import csv
import json
import re

from ph_privacy_guide import catalogue
from ph_privacy_guide.config import DRAFT_LABEL, PROCESSED, REPORTS

STATUS_VERBS_RE = re.compile(r"\b(repeal\w*|supersed\w*|amend\w*|supplement\w*|revok\w*|rescind\w*|clarif\w+)\b", re.I)
INSTRUMENT_RE = re.compile(
    r"(?:NPC\s+)?(?:Circular|Advisory|Advisories|Memorandum|Order)(?:\s+No\.?)?\s*\d{2,4}\s*[-–]\s*\d{2,3}"
    r"|Republic Act(?:\s+No\.?)?\s*\d+|R\.?A\.?\s*(?:No\.?\s*)?\d{4,5}"
    r"|\bIRR\b|Implementing Rules and Regulations|\bDPA\b|Data Privacy Act"
    r"|Human Security Act|Executive Order\s+No\.?\s*\d+", re.I)
GENERIC_RE = re.compile(r"contrary to|inconsistent with|inconsistent herewith", re.I)
SENTENCE_RE = re.compile(r"(?<=[.;:])\s+(?=[A-Z“\"(])")
REMARK_FIELDS = ["doc_id", "citation", "kind", "pages", "class", "verb", "instruments", "sentence"]


def sentences(text: str) -> list[str]:
    flat = re.sub(r"\s+", " ", re.sub(r"([a-z])-\n([a-z])", r"\1\2", text))
    return SENTENCE_RE.split(flat)


def classify(sentence: str) -> tuple[str, list[str]]:
    named = sorted({re.sub(r"\s+", " ", m.group(0)) for m in INSTRUMENT_RE.finditer(sentence)}, key=str.lower)
    if GENERIC_RE.search(sentence) and not re.search(r"Circular(?:\s+No\.?)?\s*\d|Advisory(?:\s+No\.?)?\s*\d", sentence):
        return "generic", named
    return ("named" if named else "generic"), named


def scan() -> list[dict]:
    hits: list[dict] = []
    for row in catalogue.load():
        if row["in_corpus"] != "yes":
            continue
        with open(PROCESSED / "sections" / f"{row['doc_id']}.jsonl") as f:
            records = [json.loads(line) for line in f]
        for rec in records:
            for sentence in sentences(rec["text"]):
                verb = STATUS_VERBS_RE.search(sentence)
                if not verb:
                    continue
                kind, named = classify(sentence)
                pages = f"{rec['page_start']}" if rec["page_start"] == rec["page_end"] else f"{rec['page_start']}-{rec['page_end']}"
                hits.append({"doc_id": rec["doc_id"], "citation": rec["citation"], "kind": rec["kind"], "pages": pages,
                             "class": kind, "verb": verb.group(0).lower(), "instruments": "; ".join(named), "sentence": sentence.strip()})
    return hits


def main() -> None:
    hits = scan()
    REPORTS.mkdir(exist_ok=True)
    with open(REPORTS / "status_language_scan.csv", "w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=REMARK_FIELDS, lineterminator="\n")
        w.writeheader()
        w.writerows(hits)
    named = [h for h in hits if h["class"] == "named"]
    generic = [h for h in hits if h["class"] == "generic"]
    md = ["# Repeal, supersede, amend and supplement language", "",
          "Generated by `scripts/scan_status_language.py` over all 28 corpus documents, including preambles, footnotes "
          "and annexes. The scan changes no status. Words searched: repeal, supersede, amend, supplement, revoke, rescind, "
          f"clarify. Line breaks are flattened. The draft circular is {DRAFT_LABEL}, so its wording changes nothing.", "",
          f"{len(named)} sentences name an instrument. {len(generic)} are generic or name nothing.", "",
          "## Sentences naming an instrument", "", "| Document | Where | Pages | Verb | Exact sentence |", "|---|---|---|---|---|"]
    md += [f"| {h['doc_id']} | {h['citation']} ({h['kind']}) | {h['pages']} | {h['verb']} | {h['sentence'].replace('|', '/')} |" for h in named]
    md += ["", "## Generic sentences (never a basis for a status change)", "", "| Document | Where | Pages | Verb | Exact sentence |", "|---|---|---|---|---|"]
    md += [f"| {h['doc_id']} | {h['citation']} ({h['kind']}) | {h['pages']} | {h['verb']} | {h['sentence'].replace('|', '/')} |" for h in generic]
    (REPORTS / "status_language_scan.md").write_text("\n".join(md) + "\n")
    print(f"{len(named)} named, {len(generic)} generic")
    for h in named:
        print(f"[{h['doc_id'][:34]}] {h['citation'][:38]} ({h['kind']}) p{h['pages']} <{h['verb']}> {h['sentence'][:330]}")
    print("--- generic")
    for h in generic:
        print(f"[{h['doc_id'][:34]}] {h['citation'][:30]} p{h['pages']} <{h['verb']}> {h['sentence'][:130]}")


if __name__ == "__main__":
    main()
